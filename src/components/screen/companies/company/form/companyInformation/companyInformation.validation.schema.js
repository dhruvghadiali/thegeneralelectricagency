import * as Yup from "yup";

import {
  COMPANY_INFORMATION_ADDRESS_MAX_LENGTH,
  COMPANY_INFORMATION_ADDRESS_MIN_LENGTH,
  COMPANY_INFORMATION_EMAIL_MAX_LENGTH,
  COMPANY_INFORMATION_EMAIL_MIN_LENGTH,
  COMPANY_INFORMATION_GST_PATTERN,
  COMPANY_INFORMATION_NAME_MAX_LENGTH,
  COMPANY_INFORMATION_NAME_MIN_LENGTH,
  COMPANY_INFORMATION_PAN_PATTERN,
  COMPANY_INFORMATION_PHONE_PATTERN,
  COMPANY_INFORMATION_PINCODE_PATTERN,
  COMPANY_INFORMATION_SUPPORTED_STATES,
  COMPANY_INFORMATION_SUPPORTED_TYPES,
  COMPANY_INFORMATION_WEBSITE_MAX_LENGTH,
  COMPANY_INFORMATION_WEBSITE_MIN_LENGTH,
  COMPANY_INFORMATION_WEBSITE_PATTERN,
} from "@screenComponent/companies/company/form/companyInformation/companyInformation.validation.constants";
import { COMPANY_INFORMATION_VALIDATION_MESSAGES as MESSAGES } from "@screenComponent/companies/company/form/companyInformation/companyInformation.validation.messages";

const optionalText = () =>
  Yup.string()
    .trim()
    .transform((value) => (value === "" ? undefined : value));

export const companyInformationValidationSchema = Yup.object({
  companyName: Yup.string()
    .trim()
    .min(COMPANY_INFORMATION_NAME_MIN_LENGTH, MESSAGES.COMPANY_NAME_MIN)
    .max(COMPANY_INFORMATION_NAME_MAX_LENGTH, MESSAGES.COMPANY_NAME_MAX)
    .required(MESSAGES.COMPANY_NAME_REQUIRED),
  companyType: Yup.string()
    .oneOf(
      COMPANY_INFORMATION_SUPPORTED_TYPES,
      MESSAGES.COMPANY_TYPE_INVALID,
    )
    .required(MESSAGES.COMPANY_TYPE_REQUIRED),
  email: optionalText()
    .min(COMPANY_INFORMATION_EMAIL_MIN_LENGTH, MESSAGES.EMAIL_MIN)
    .max(COMPANY_INFORMATION_EMAIL_MAX_LENGTH, MESSAGES.EMAIL_MAX)
    .email(MESSAGES.EMAIL_INVALID),
  phoneNumber: optionalText().matches(
    COMPANY_INFORMATION_PHONE_PATTERN,
    MESSAGES.PHONE_INVALID,
  ),
  gstNumber: optionalText()
    .uppercase()
    .matches(COMPANY_INFORMATION_GST_PATTERN, MESSAGES.GST_INVALID),
  panNumber: optionalText()
    .uppercase()
    .matches(COMPANY_INFORMATION_PAN_PATTERN, MESSAGES.PAN_INVALID),
  website: optionalText()
    .min(COMPANY_INFORMATION_WEBSITE_MIN_LENGTH, MESSAGES.WEBSITE_MIN)
    .max(COMPANY_INFORMATION_WEBSITE_MAX_LENGTH, MESSAGES.WEBSITE_MAX)
    .matches(COMPANY_INFORMATION_WEBSITE_PATTERN, MESSAGES.WEBSITE_INVALID),
  address: optionalText()
    .min(COMPANY_INFORMATION_ADDRESS_MIN_LENGTH, MESSAGES.ADDRESS_MIN)
    .max(COMPANY_INFORMATION_ADDRESS_MAX_LENGTH, MESSAGES.ADDRESS_MAX)
    .required(MESSAGES.ADDRESS_REQUIRED),
  state: optionalText()
    .oneOf(COMPANY_INFORMATION_SUPPORTED_STATES, MESSAGES.STATE_INVALID)
    .required(MESSAGES.STATE_REQUIRED),
  pincode: optionalText()
    .matches(
      COMPANY_INFORMATION_PINCODE_PATTERN,
      MESSAGES.PINCODE_INVALID,
    )
    .required(MESSAGES.PINCODE_REQUIRED),
});
